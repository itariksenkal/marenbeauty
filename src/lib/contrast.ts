/**
 * WCAG 2.1 relative luminance and contrast ratio, sRGB.
 *
 * Pure. Used by the styleguide to compute every pairing from the real token
 * values rather than repeating the numbers in docs/DESIGN-SYSTEM.md §1.4,
 * which would drift the first time a hex changed.
 */

export type WcagLevel = 'AAA' | 'AA' | 'AA Large' | 'Fail';

function channel(value: number): number {
  const c = value / 255;
  return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
}

export function relativeLuminance(hex: string): number {
  const n = parseInt(hex.replace('#', ''), 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

export function contrastRatio(a: string, b: string): number {
  const la = relativeLuminance(a);
  const lb = relativeLuminance(b);
  const lighter = Math.max(la, lb);
  const darker = Math.min(la, lb);
  return (lighter + 0.05) / (darker + 0.05);
}

/** Level for normal body text. Large text and non-text pass at 3:1. */
export function wcagLevel(ratio: number): WcagLevel {
  if (ratio >= 7) return 'AAA';
  if (ratio >= 4.5) return 'AA';
  if (ratio >= 3) return 'AA Large';
  return 'Fail';
}
